//! 빌드 스크립트.
//!
//! ## 아이콘을 바꾸면 여기서 다시 빌드되어야 한다
//!
//! 실행파일 안의 아이콘은 `tauri_build::build()`가 컴파일할 때 넣는다.
//! 그런데 tauri-build 는 아이콘 파일을 다시 빌드할 까닭으로 알려 주지 않아서,
//! 아이콘만 바꾸고 다시 빌드하면 **설치파일 아이콘만 바뀌고 앱 아이콘은
//! 예전 것이 그대로 남는다.** makensis 는 빌드할 때마다 `icon.ico` 를 새로
//! 읽지만 Rust 쪽은 캐시를 쓰기 때문이다.
//!
//! 설치해서 시작 메뉴에서는 새 아이콘이 보이는데 작업표시줄만 예전 아이콘인
//! 상태가 되므로 알아채기 어렵다. 실제로 한 번 겪었다.
//!
//! 그래서 아이콘 파일을 바꾸면 다시 빌드하도록 여기에 적어 둔다.

fn main() {
    for icon in [
        "icons/icon.ico",
        "icons/32x32.png",
        "icons/128x128.png",
        "icons/128x128@2x.png",
    ] {
        println!("cargo:rerun-if-changed={icon}");
    }

    tauri_build::build()
}
